/** Extracts inner SVG path geometry from an icon file. */
function extractBody(name) {
  const svg = readFileSync(resolve(iconDir, `${name}.svg`), 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));

  return inner
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join('')
    .replace(/\s*\/>/g, '/>')
    .replace(/>\s+</g, '><');
}

const version = JSON.parse(
  readFileSync(resolve(root, 'node_modules/lucide-static/package.json'), 'utf8'),
).version;

const entries = Object.entries(ICONS)
  .map(([name, use]) => `  /** ${use} */\n  '${name}':\n    '${extractBody(name)}',`)
  .join('\n');

const source = `/**
 * Lucide icon geometry.
 *
 * GENERATED by scripts/build-icons.mjs from lucide-static ${version} (ISC).
 * Do not edit directly: add icons to ICONS in scripts/build-icons.mjs.
 */

export const ICON_PATHS = {
${entries}
} as const;

export type IconName = keyof typeof ICON_PATHS;
`;

writeFileSync(outFile, source);
console.log(`icons: wrote ${Object.keys(ICONS).length} to ${outFile}`);
